"""Builds src/data/realRequirements.ts from raw einsaetze.json extracts in scripts/mc-raw/.
Missions not present in the raw extracts fall back to scripts/mc-requirements-old.txt."""
import re, glob
KEY={'firetrucks':'ft','platform_trucks':'pt','battalion_chief_vehicles':'bc','mobile_command_vehicles':'mc','elw3':'mc',
'mobile_air_vehicles':'ma','water_tankers':'wt','heavy_rescue_vehicles':'hr','technical_rescue':'tr','hazmat_vehicles':'hz',
'fire_investigation':'fi','police_cars':'pc','sheriff':'sv','oneof_police_patrol_or_swat':'pc','k9':'k9','police_helicopters':'ph',
'swat_armored_vehicle':'sw','arff':'arff','ambulances':'am','boats':'bt','large_rescue_boat':'bt','large_fire_boat':'fb',
'brush_truck':'br','fbi':'fd','dea_clan_lab':'fd','dea_unit':'fd','atf_lab_vehicle':'fd','atf_unit':'fd','fbi_bomb':'bo',
'police_drone':'dn','fbi_drone':'dn','oneof_fire_investigation_or_fbi_drone':'dn','investigation':'iv','civil_patrolcar':'iv',
'crime_scene_unit':'csu','game_warden':'gw','foam':'fo','coastal_boat':'cs','large_coastal_boat':'cs','coastal_helicopter':'cht',
'fwk':'fwk','flood_equipment':'fl','detention_unit':'pv','riot_police':'rt','mcc':'pm','elw_police':'pm','water_rescue':'lg',
'police_boat':'pb'}
IGNORE={'riot_police_trailer','coastal_plane','fire_aviation','coastal_command','brush_air_command','none','','-'}
SEASON=re.compile(r'christmas|halloween|pumpkin|zombie|witch|frankenstein|candy|easter|bunny|valentin|leprechaun|patrick|shamrock|firework|firecracker|new year|thanksgiving|turkey|carnival|santa|advent|snowman|cupid|teddy|proposing|heart stolen|broken heart|butterflies|chocolate|soccer ball|corner flag|captain armband|trophy|team bus|celebrating|hitting bar|after diving|ice spray|goal fell|anniversary|fondue',re.I)
raw={}; unknown=set()
for f in sorted(glob.glob('scripts/mc-raw/*.txt')):
  for line in open(f):
    line=line.strip()
    if not line: continue
    parts=line.split(';')
    if len(parts)!=7: print('BAD',f,line[:60]); continue
    _id,name,cr,rq,pt,pr,pre=parts
    if '-' in _id or '/' in _id or SEASON.search(name): continue
    codes={}
    for tok in rq.split(','):
      if '=' not in tok: continue
      k,v=tok.split('=',1); v=int(v)
      if k in IGNORE: continue
      if k=='smoke_jumper_personnel': c,v='cc',max(1,-(-v//12))
      else: c=KEY.get(k) or ('ft' if k.startswith('oneof_') else None)
      if not c: unknown.add(k); continue
      codes[c]=codes.get(c,0)+v
    pt=pt.replace('?','').replace('–','-').strip()
    if pt in('-','none',''): a,b='0','0'
    else:
      if '-' not in pt: pt='0-'+pt
      a,b=pt.split('-',1); a=a if a.isdigit() else '0'; b=b if b.isdigit() else '0'
    pr=pr if pr.isdigit() else '0'
    if not codes and int(b)==0: continue
    if '/' in pre: nums=[int(x) if x.isdigit() else 0 for x in pre.split('/')]
    else:
      nums=[0,0,0]
      for k,v in re.findall(r'(\w+)[=:](\d+)',pre):
        i={'F':0,'fire_stations':0,'A':1,'rescue_stations':1,'P':2,'police_stations':2}.get(k)
        if i is not None: nums[i]=int(v)
    cr=cr if cr.isdigit() else '0'
    nm=name.strip().replace('–','-'); key=nm.lower()
    if key in raw: continue
    raw[key]=f"{nm}|{cr}|{','.join(f'{k}{v}' for k,v in codes.items())}|{a}-{b}|{pr}|{nums[0]}/{nums[1]}/{nums[2]}"
old=[l.rstrip('\n') for l in open('scripts/mc-requirements-old.txt') if l.strip() and not l.startswith('#')]
out=list(raw.values()); kept=0
for l in old:
  k=l.split('|')[0].strip().lower()
  if k not in raw and not SEASON.search(k): out.append(l); kept+=1
print('raw',len(raw),'old kept',kept,'total',len(out),'unknown',unknown)
open('scripts/mc-requirements.txt','w').write("# name|credits|requirements|patients|prisoners|prereq fire/ems/police (generated by build-requirements.py)\n"+'\n'.join(out)+'\n')
body='\n'.join(out).replace('\\','\\\\').replace('`','\\`').replace('${','\\${')
open('src/data/realRequirements.ts','w').write("// Per-mission vehicle requirements, patients, prisoners and station prerequisites,\n// transcribed from https://www.missionchief.com/einsaetze.json (seasonal events skipped).\n// Format: name|credits|requirements|patients min-max|prisoners max|fire/ems/police stations\nexport const REAL_REQUIREMENTS = `\n"+body+"\n`;\n")
